        """
        Unified correlated movement envelope for absolute-angle, relative-step
        and stop operations. This is the single agreed request
        envelope for ground-issued movement; ACTUATOR_SETPOINT keeps
        its existing semantics unchanged for the isolated motor bench.
        Receivers must reject stale, duplicate, unauthorized, out-of-
        range, or session-mismatched requests without moving the
        actuator.

        request_id                : Ground-generated identifier unique within ground_session, echoed in REQUEST_RESULT for correlation. Monotonic per session where practical. (type:uint32_t)
        ground_session            : Random per-connection ground session identifier. A reconnect selects a new value; queued movement carrying an old session is invalid. (type:uint32_t)
        delta_cdeg                : Absolute target angle for MOVEMENT_OPCODE_ABSOLUTE, signed relative delta resolved once against valid fresh feedback for MOVEMENT_OPCODE_STEP, and zero for MOVEMENT_OPCODE_STOP. [cdeg] (type:int16_t)
        timeout_ms                : Freshness timeout after reception. Zero uses the receiver's configured default. [ms] (type:uint16_t)
        max_rate_cdeg_s           : Maximum slew rate for this movement. Zero uses the receiver's configured default. [cdeg/s] (type:uint16_t)
        target_system             : System ID of the intended recipient. (type:uint8_t)
        target_component          : Component ID of the intended recipient. (type:uint8_t)
        actuator                  : Actuator to command. (type:uint8_t, values:ACTUATOR_ID)
        opcode                    : Requested operation. (type:uint8_t, values:MOVEMENT_OPCODE)
        control_source            : Authority under which this request was produced. (type:uint8_t, values:CONTROL_SOURCE)

        """
        return MAVLink_actuator_request_message(request_id, ground_session, delta_cdeg, timeout_ms, max_rate_cdeg_s, target_system, target_component, actuator, opcode, control_source)

